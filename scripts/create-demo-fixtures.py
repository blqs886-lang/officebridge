"""Regenerate small synthetic examples; requires python-pptx and openpyxl.

No user documents are used. Runtime application has no Python dependency.
"""
from pathlib import Path
from base64 import b64encode
from datetime import datetime
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.chart.data import CategoryChartData
from pptx.enum.chart import XL_CHART_TYPE
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "public" / "examples"
OUT.mkdir(parents=True, exist_ok=True)

prs = Presentation()
prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
prs.core_properties.title = "OfficeBridge synthetic compatibility sample"
prs.core_properties.author = "OfficeBridge contributors"
prs.core_properties.last_modified_by = "OfficeBridge contributors"
prs.core_properties.created = datetime(2026, 1, 1)
prs.core_properties.modified = datetime(2026, 1, 1)
for number, title in enumerate(["跨系统，保留可编辑内容", "图表也应该继续可编辑"]):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = RGBColor.from_string("F5F7F3")
    box = slide.shapes.add_textbox(Inches(.7), Inches(.6), Inches(12), Inches(.8))
    run = box.text_frame.paragraphs[0].add_run()
    run.text, run.font.name, run.font.size = title, "PingFang SC", Pt(30)
    run.font.color.rgb = RGBColor.from_string("21382C")
    if number == 0:
        text = slide.shapes.add_textbox(Inches(.75), Inches(2.0), Inches(11.5), Inches(2.8))
        for index, line in enumerate(["OfficeBridge · editable-first", "这是一份合成演示稿，不含任何个人资料。", "字体：PingFang SC / Helvetica Neue。", "替换字体后，文字和图表仍可以编辑。"]):
            p = text.text_frame.paragraphs[0] if index == 0 else text.text_frame.add_paragraph()
            p.text = line
            p.font.name = "Helvetica Neue" if index == 0 else "PingFang SC"
            p.font.size = Pt(24 if index == 0 else 20)
            p.space_after = Pt(15)
    else:
        data = CategoryChartData()
        data.categories = ["一月", "二月", "三月"]
        data.add_series("合成数据", (12, 18, 24))
        slide.shapes.add_chart(XL_CHART_TYPE.COLUMN_CLUSTERED, Inches(.8), Inches(2), Inches(8), Inches(4.5), data)
        box = slide.shapes.add_textbox(Inches(9.2), Inches(2.5), Inches(3), Inches(2))
        box.text_frame.text = "真实的 Office 图表\n内嵌数据保留\n未栅格化为图片"
        for p in box.text_frame.paragraphs:
            p.font.name, p.font.size = "PingFang SC", Pt(19)
    slide.notes_slide.notes_text_frame.text = "Synthetic sample. Check the resulting copy in your target Windows Office version."
pptx_path = OUT / "officebridge-demo.pptx"
prs.save(pptx_path)

wb = Workbook()
wb.properties.creator = "OfficeBridge contributors"
wb.properties.lastModifiedBy = "OfficeBridge contributors"
wb.properties.created = wb.properties.modified = datetime(2026, 1, 1)
ws = wb.active
ws.title = "预算示例"
for row in [["项目", "预算", "实际", "差额"], ["设计", 1200, 1100, "=B2-C2"],
            ["开发", 3000, 2900, "=B3-C3"], ["测试", 800, 750, "=B4-C4"],
            ["合计", "=SUM(B2:B4)", "=SUM(C2:C4)", "=SUM(D2:D4)"]]:
    ws.append(row)
for row in ws:
    for cell in row:
        cell.font = Font(name="PingFang SC", size=12, bold=cell.row == 1)
        cell.alignment = Alignment(vertical="center")
        if cell.row == 1:
            cell.fill = PatternFill("solid", fgColor="21382C")
            cell.font = Font(name="PingFang SC", size=12, bold=True, color="FFFFFF")
for col in "ABCD": ws.column_dimensions[col].width = 20
for row in range(1, 6): ws.row_dimensions[row].height = 28
ws.freeze_panes = "B2"
ws.auto_filter.ref = "A1:D4"
ws.print_options.horizontalCentered = True
ws.print_area = "A1:D5"
ws.sheet_properties.pageSetUpPr.fitToPage = True
ws.page_setup.fitToWidth, ws.page_setup.fitToHeight = 1, 0
notes = wb.create_sheet("编号与说明")
for row in [["编号（文本）", "说明"], ["00123", "前导零应保留"],
            ["12345678901234567890", "长编号保持文本，不转成数字"],
            ["可编辑内容", "工具不会改公式、值、日期或列宽"]]: notes.append(row)
notes.column_dimensions["A"].width = 28
notes.column_dimensions["B"].width = 48
for row in notes:
    for cell in row: cell.font = Font(name="Helvetica Neue", size=12)
xlsx_path = OUT / "officebridge-demo.xlsx"
wb.save(xlsx_path)

data = {"pptx": b64encode(pptx_path.read_bytes()).decode(), "xlsx": b64encode(xlsx_path.read_bytes()).decode()}
source = "// Generated by scripts/create-demo-fixtures.py. Synthetic data only.\nimport { readArchive, writeArchive } from './archive.js';\nimport { normalizeFontOptions } from './fonts.js';\n\nconst samples = " + repr(data).replace("'", '"') + ";\n\n"
source += """export function createDemo(format = 'pptx', options = {}) {
  if (!Object.hasOwn(samples, format)) throw new Error('Unknown example format');
  const { fontProfile } = normalizeFontOptions(options);
  const bytes = Uint8Array.from(atob(samples[format]), c => c.charCodeAt(0));
  if (fontProfile === 'windows-office') return bytes;
  // Transform only our bundled synthetic fixture, never user input. The original
  // default demo remains byte-for-byte identical to the published sample.
  const { entries } = readArchive(bytes);
  const targets = { 'PingFang SC': 'Microsoft YaHei', 'Helvetica Neue': 'Segoe UI' };
  const encoder = new TextEncoder(), decoder = new TextDecoder();
  for (const [part, data] of entries) {
    if (!part.endsWith('.xml')) continue;
    const original = decoder.decode(data);
    const changed = original.replace(/(typeface|val)="(PingFang SC|Helvetica Neue)"/g,
      (_, key, face) => `${key}="${targets[face]}"`)
      .replace('字体：PingFang SC / Helvetica Neue。', '字体：Microsoft YaHei / Segoe UI。')
      .replace('target Windows Office version', 'target Mac Office version');
    if (changed !== original) entries.set(part, encoder.encode(changed));
  }
  return writeArchive(entries);
}
"""
(ROOT / "src" / "engine" / "demo.js").write_text(source)
print(f"Generated synthetic examples: {pptx_path.stat().st_size} + {xlsx_path.stat().st_size} bytes")
